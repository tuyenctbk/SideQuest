import os

def escape_xml(s):
    # XML special characters
    s = s.replace('&', '&amp;')
    s = s.replace('<', '&lt;')
    s = s.replace('>', '&gt;')
    # Android resource escaping for single and double quotes
    s = s.replace("'", "\\'")
    s = s.replace('"', '\\"')
    if s.startswith('@'):
        s = '\\' + s
    if s.startswith('?'):
        s = '\\' + s
    return s

def write_strings_xml(folder_name, string_dict):
    out_dir = os.path.join('app/src/main/res', folder_name)
    os.makedirs(out_dir, exist_ok=True)
    out_file = os.path.join(out_dir, 'strings.xml')
    with open(out_file, 'w', encoding='utf-8') as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n')
        f.write('<resources>\n')
        for key, val in string_dict.items():
            f.write(f'    <string name="{key}">{escape_xml(val)}</string>\n')
        f.write('</resources>\n')
    print(f"Successfully generated {out_file} ({len(string_dict)} strings)")

